// Original modular biped artwork and part statistics for the Garage.
// Every part owns an immutable neutral base plus independently recolorable
// Primary (8), Secondary (6), and Accent (5) masks of matching dimensions.

function createAttachedCorePartArt(
    base: Image,
    primary: Image,
    secondary: Image,
    accent: Image,
    attachX: number,
    attachY: number,
    footY: number
) {
    let art = new CorePartArt(base, primary, secondary, accent)
    art.attachX = attachX
    art.attachY = attachY
    art.footY = footY
    return art
}

function createBodyCorePartArt(
    base: Image,
    primary: Image,
    secondary: Image,
    accent: Image,
    neckX: number,
    neckY: number,
    shoulderX: number,
    shoulderY: number,
    hipX: number,
    hipY: number
) {
    let art = new CorePartArt(base, primary, secondary, accent)
    art.neckX = neckX
    art.neckY = neckY
    art.shoulderX = shoulderX
    art.shoulderY = shoulderY
    art.hipX = hipX
    art.hipY = hipY
    return art
}

